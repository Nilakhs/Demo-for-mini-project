/*
 * generate_config.c
 *
 * This is the PRODUCER program.
 * It generates "generated_config.h" — an artifact that consumer.c depends on.
 *
 * Run this BEFORE compiling consumer.c.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    FILE *fp = fopen("generated_config.h", "w");
    if (fp == NULL) {
        fprintf(stderr, "generate_config: ERROR — could not create generated_config.h\n");
        return 1;
    }

    fprintf(fp, "/*\n");
    fprintf(fp, " * generated_config.h\n");
    fprintf(fp, " *\n");
    fprintf(fp, " * AUTO-GENERATED by generate_config\n");
    fprintf(fp, " * DO NOT EDIT MANUALLY\n");
    fprintf(fp, " *\n");
    fprintf(fp, " * This file is a BUILD ARTIFACT — it is produced by running generate_config\n");
    fprintf(fp, " * and is required by consumer.c at compile time.\n");
    fprintf(fp, " */\n\n");
    fprintf(fp, "#ifndef GENERATED_CONFIG_H\n");
    fprintf(fp, "#define GENERATED_CONFIG_H\n\n");
    fprintf(fp, "#define GENERATED_MESSAGE \"Generated successfully\"\n");
    fprintf(fp, "#define GENERATOR_VERSION \"1.0.0\"\n");
    fprintf(fp, "#define BUILD_ARTIFACT    1\n\n");
    fprintf(fp, "#endif /* GENERATED_CONFIG_H */\n");

    fclose(fp);
    printf("generate_config: generated_config.h created\n");
    return 0;
}
